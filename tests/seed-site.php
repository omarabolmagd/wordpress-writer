$created = 0;
foreach ( $posts as $i => $p ) {
	if ( get_posts( array( 'post_type' => 'post', 'title' => $p[0], 'post_status' => 'any', 'fields' => 'ids' ) ) ) {
		continue;
	}
	$content = $para( $p[2] ) . "\n\n" . $para( $p[3] );
	if ( 5 === $i ) {
		// One classic-editor post without blocks or <p> tags.
		$content = $p[2] . "\n\n" . $p[3];
	}
	$id = wp_insert_post(
		array(
			'post_title'    => $p[0],
			'post_content'  => $content,
			'post_status'   => 'publish',
			'post_type'     => 'post',
			'post_author'   => 1,
			'post_category' => array( $ids[ $p[1] ] ),
			'post_date'     => gmdate( 'Y-m-d H:i:s', time() - ( 20 - $i ) * DAY_IN_SECONDS ),
		)
	);
	if ( 7 === $i ) {
		update_post_meta( $id, '_elementor_edit_mode', 'builder' );
	}
	++$created;
}

