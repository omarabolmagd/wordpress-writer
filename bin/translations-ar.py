root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
pot = open(os.path.join(root, "languages/ana-afdal-writer.pot"), encoding="utf-8").read()

blocks = pot.split("\n\n")
out = []
missing = []
for block in blocks:
    m = re.search(r'^msgid ((?:".*"\n?)+)', block, re.M)
    if not m:
        out.append(block)
        continue
    msgid = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)))
    if msgid == "":
        header = block.replace('"Language: \\n"', '"Language: ar\\n"')
        if "Plural-Forms" not in header:
            header = header.replace('"Content-Transfer-Encoding: 8bit\\n"', '"Content-Transfer-Encoding: 8bit\\n"\n"Plural-Forms: nplurals=6; plural=(n==0 ? 0 : n==1 ? 1 : n==2 ? 2 : n%100>=3 && n%100<=10 ? 3 : n%100>=11 ? 4 : 5);\\n"')
        out.append(header)
        continue
    tr = AR.get(msgid)
    if tr is None:
        missing.append(msgid)
        out.append(block)
        continue
    out.append(re.sub(r'msgstr ""\s*$', 'msgstr "' + tr + '"', block.rstrip("\n")))

open(os.path.join(root, "languages/ana-afdal-writer-ar.po"), "w", encoding="utf-8").write("\n\n".join(out) + "\n")
print(f"{len(AR)} translations, {len(missing)} missing")
for m in missing:
    print("MISSING:", m)
